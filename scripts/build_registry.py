"""Expand registry/features.py into features/<id>/manifest.json and COVERAGE.md.

Run: uv run scripts/build_registry.py
Status is read back from existing manifests so build/smoke scripts can promote
a feature (planned -> built -> tested) without this script resetting it.
"""
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from registry.features import BASES, FEATURES, MODEL_ROSTER  # noqa: E402
from registry.wiring import WIRING  # noqa: E402

ORDER = {"planned": 0, "built": 1, "tested": 2}


def models_in(ui_workflow: Path) -> list[str]:
    """Model files a template references (any *.safetensors/ckpt/gguf string in its widget values)."""
    found = re.findall(r"[\w.\-]+\.(?:safetensors|ckpt|pt|gguf)", ui_workflow.read_text(encoding="utf-8"))
    return sorted(set(found))


def write_manifests():
    for feat in FEATURES:
        d = ROOT / "features" / feat["id"]
        d.mkdir(parents=True, exist_ok=True)
        mf = d / "manifest.json"
        old = json.loads(mf.read_text(encoding="utf-8")) if mf.exists() else {}
        merged = {**old, **feat}  # registry owns the descriptive fields; keep anything a build step added
        merged["status"] = max(old.get("status", "planned"), feat["status"], key=ORDER.get)
        wiring = WIRING.get(feat["id"])
        if wiring and (d / "workflow_api.json").exists():
            fid = feat["id"]
            merged["workflow"] = {
                "template": wiring["template"], "api": f"features/{fid}/workflow_api.json",
                "ui": f"features/{fid}/workflow_ui.json", "inputs": wiring["inputs"],
                "outputs": wiring["outputs"], "models": wiring.get("models") or models_in(d / "workflow_ui.json"),
                **({"output_kind": wiring["output_kind"]} if wiring.get("output_kind") else {}),
                "verified": bool(wiring.get("verified_via")),
            }
            if wiring.get("verified_via"):
                merged["workflow"]["verified_via"] = wiring["verified_via"]
                merged["workflow"]["examples"] = wiring.get("examples", [])
            merged["status"] = max(merged["status"], "tested" if wiring.get("verified_via") else "built", key=ORDER.get)
        mf.write_text(json.dumps(merged, indent=2) + "\n", encoding="utf-8")


def load():
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((ROOT / "features").glob("*/manifest.json"))]


def write_coverage(feats):
    tiers = Counter(f["tier"] for f in feats)
    units = Counter()
    for f in feats:
        units[f["tier"]] += f.get("count", 1)
    stat = Counter(f["status"] for f in feats)
    out = ["# Coverage: Higgsfield -> OpenSfield", "",
           "Generated by `scripts/build_registry.py`. Do not edit by hand.", "",
           f"**{len(feats)} feature modules** ({sum(units.values())} user-facing presets/modes). "
           f"Tier A {tiers['A']} / B {tiers['B']} / C {tiers['C']} modules; "
           f"status: {dict(stat)}.", "",
           "Tier A = hand-built + smoke-tested via comfy-sdk. B = generated from a base workflow + preset data. "
           "C = mapped only / out of scope. Track `partner` items live only in the optional `partner/` pack.", "",
           "Status: `planned` = mapped only. `built` = workflow wired from the official Comfy template and statically "
           "checked, **not yet run end to end**. `tested` = rendered successfully on a real server.", ""]
    by = defaultdict(list)
    for f in feats:
        by[f["studio"]].append(f)
    for studio, items in by.items():
        out += [f"## {studio}", "", "| Feature | Higgsfield source | Tier | Track | Base graphs | Count | Status |", "|---|---|---|---|---|---|---|"]
        for f in items:
            out.append(f"| {f['name']} | {f['higgsfield']} | {f['tier']} | {f['track']} | {', '.join(f['base']) or '-'} | {f.get('count', 1)} | {f['status']} |")
        notes = [f"- **{f['id']}**: {f['note']}" for f in items if f.get("note")]
        out += [""] + notes + [""] if notes else [""]
    out += ["## Model roster -> open stand-in", "", "| Family | Higgsfield model ids | OpenSfield stand-in |", "|---|---|---|"]
    n = 0
    for fam, (ids, eq) in MODEL_ROSTER.items():
        n += len(ids)
        out.append(f"| {fam} | {', '.join(ids)} | {eq} |")
    out += ["", f"{n} model ids mapped.", "", "## Base graphs", "", "| id | description |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in BASES.items()]
    (ROOT / "COVERAGE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    return len(feats), n


if __name__ == "__main__":
    write_manifests()
    nf, nm = write_coverage(load())
    print(f"wrote {nf} manifests, {nm} model ids mapped -> COVERAGE.md")
